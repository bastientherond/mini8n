//! Documentation du langage : variables, fonctions et méthodes proposées par
//! l'autocomplétion de l'éditeur. Chaque exemple est vérifié par les tests.

use serde::Serialize;

#[derive(Debug, Clone, Serialize)]
pub struct Doc {
    pub name: &'static str,
    /// `variable`, `function`, `method`, `property` ou `constant`.
    pub kind: &'static str,
    /// Ce sur quoi elle s'applique : `global`, `string`, `number`, `list`, `object`,
    /// `date`, `any`, `Math`, `JSON`, `Object`, `input` (`$input`/`$('…')`), `item`, `legacy`.
    pub on: &'static str,
    /// Paramètres (sans le nom), ex. `(début, fin?)`.
    #[serde(skip_serializing_if = "str::is_empty")]
    pub args: &'static str,
    pub returns: &'static str,
    pub info: &'static str,
    pub example: &'static str,
    /// Résultat de l'exemple (JSON), vide si l'exemple dépend des données.
    #[serde(skip_serializing_if = "str::is_empty")]
    pub result: &'static str,
}

#[allow(clippy::too_many_arguments)] // table de données compacte
const fn d(
    name: &'static str,
    kind: &'static str,
    on: &'static str,
    args: &'static str,
    returns: &'static str,
    info: &'static str,
    example: &'static str,
    result: &'static str,
) -> Doc {
    Doc {
        name,
        kind,
        on,
        args,
        returns,
        info,
        example,
        result,
    }
}

