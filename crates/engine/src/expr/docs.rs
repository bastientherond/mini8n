/// Méthodes reconnues (tous types confondus).
pub fn is_method(name: &str) -> bool {
    DOCS.iter().any(|d| {
        d.kind == "method"
            && d.name == name
            && matches!(
                d.on,
                "string" | "number" | "list" | "object" | "date" | "any"
            )
    })
}

/// Propriétés reconnues sur des valeurs (hors champs d'objets).
pub fn methods_for(kind: &str) -> Vec<&'static str> {
    DOCS.iter()
        .filter(|d| (d.on == kind || d.on == "any") && matches!(d.kind, "method" | "property"))
        .map(|d| d.name)
        .collect()
}
